"""MediaMTX config and FFmpeg command of a slot's sim video test source.

One MediaMTX per slot with a path ``uav<n>`` per UAV whose ``runOnDemand``
publishes an H.264 test pattern over RTSP TCP (gcs_video_streams.md, section
6). Only the slot's three allocated listeners open, all on loopback: RTSP TCP,
WebRTC HTTP (WHEP) and WebRTC UDP. Everything else is disabled.
"""
from __future__ import annotations

import json
from pathlib import Path

from gcs.backend import instance_ports as ip

LOOPBACK = "127.0.0.1"
FRAME_WIDTH = 640
FRAME_HEIGHT = 360
FRAMERATE = 15
# One keyframe per second (design: at most 2 s) so a joining reader starts fast.
KEYFRAME_INTERVAL_FRAMES = FRAMERATE


def stream_path(uav: int) -> str:
    """The MediaMTX path of UAV *uav* (1-based within the slot)."""
    return f"uav{uav}"


def stream_label(uav: int) -> str:
    """The label drawn on the test pattern and announced as the stream name."""
    return f"SIM TEST UAV {uav}"


def stream_uri(chat: int, uav: int) -> str:
    """The RTSP URI the NavPy sim companion announces for UAV *uav*."""
    return f"rtsp://{LOOPBACK}:{ip.sim_video_rtsp_port(chat)}/{stream_path(uav)}"


def _filter_path(path: Path) -> str:
    """A font path as a filtergraph option value (the drive colon escaped)."""
    return path.as_posix().replace(":", r"\:")


def ffmpeg_publish_command(
    ffmpeg: Path, chat: int, uav: int, font: Path | None = None,
) -> str:
    """The shell command MediaMTX runs on demand for UAV *uav*.

    Written for ``sh -c`` and ``cmd /C`` alike: double quotes only.
    """
    text = f"text={stream_label(uav)}:fontcolor=white:fontsize=28:box=1:boxcolor=black@0.6:x=12:y=12"
    if font is not None:
        text = f"fontfile='{_filter_path(font)}':{text}"
    video_filter = (
        f"testsrc2=size={FRAME_WIDTH}x{FRAME_HEIGHT}:rate={FRAMERATE},drawtext={text}"
    )
    return (
        f'"{ffmpeg}" -hide_banner -loglevel error -re -f lavfi -i "{video_filter}" '
        f"-c:v libx264 -preset ultrafast -tune zerolatency -bf 0 "
        f"-g {KEYFRAME_INTERVAL_FRAMES} -sc_threshold 0 -pix_fmt yuv420p "
        f"-f rtsp -rtsp_transport tcp {stream_uri(chat, uav)}"
    )


def mediamtx_config(
    chat: int,
    uav_count: int,
    ffmpeg: Path,
    frontend_port: int,
    font: Path | None = None,
) -> str:
    """The slot's MediaMTX configuration (YAML text; JSON strings are valid YAML)."""
    origins = [f"http://localhost:{frontend_port}", f"http://{LOOPBACK}:{frontend_port}"]
    lines = [
        "# Generated by gcs.backend.sim_video_config. Do not edit.",
        "logLevel: warn",
        "logDestinations: [stdout]",
        "api: false",
        "metrics: false",
        "pprof: false",
        "playback: false",
        "rtsp: true",
        "rtspTransports: [tcp]",
        'rtspEncryption: "no"',
        f"rtspAddress: {LOOPBACK}:{ip.sim_video_rtsp_port(chat)}",
        "rtmp: false",
        "hls: false",
        "srt: false",
        "moq: false",
        "webrtc: true",
        f"webrtcAddress: {LOOPBACK}:{ip.sim_video_whep_port(chat)}",
        "webrtcEncryption: false",
        f"webrtcAllowOrigins: {json.dumps(origins)}",
        f"webrtcLocalUDPAddress: {LOOPBACK}:{ip.sim_video_webrtc_udp_port(chat)}",
        'webrtcLocalTCPAddress: ""',
        "webrtcIPsFromInterfaces: false",
        f"webrtcAdditionalHosts: [{LOOPBACK}]",
        "paths:",
    ]
    for uav in range(1, uav_count + 1):
        command = ffmpeg_publish_command(ffmpeg, chat, uav, font)
        lines += [
            f"  {stream_path(uav)}:",
            f"    runOnDemand: {json.dumps(command)}",
            "    runOnDemandRestart: true",
            "    runOnDemandStartTimeout: 15s",
            "    runOnDemandCloseAfter: 10s",
        ]
    return "\n".join(lines) + "\n"
