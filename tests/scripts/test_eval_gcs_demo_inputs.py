def test_environment_is_an_allow_list_with_pinned_threads(tmp_path):
    inherited = {
        "Path": "C:\\bin", "SystemRoot": "C:\\Windows", "WSLENV": "X/u",
        "GCS_INSTANCE_REGISTRY": "C:\\reg.json", "USERPROFILE": "C:\\Users\\u",
        "PYTHONPATH": "C:\\elsewhere", "NAVPY_SIM_DOCKS": "C:\\docks.json",
        "GCS_SIM_NAVIGATION_SPEEDUP": "99", "OMP_NUM_THREADS": "8",
    }
    env = config.build_environment(tmp_path / "s.json", tmp_path, base_environment=inherited)
    assert {"Path", "SystemRoot", "WSLENV", "GCS_INSTANCE_REGISTRY", "USERPROFILE"} <= set(env)
    for dropped in ("PYTHONPATH", "NAVPY_SIM_DOCKS", "GCS_SIM_NAVIGATION_SPEEDUP"):
        assert dropped not in env
    assert env["OMP_NUM_THREADS"] == "1"
    assert env["PYTHONHASHSEED"] == "0"
    assert env["NAVPY_SIM_CV_THREADS"] == "1"
    # The run must find the same instance registry as the shell that started it.
    assert process.registry_path(env) == process.registry_path(inherited)


