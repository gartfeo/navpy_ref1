def test_staged_root_holds_seed_defaults_and_wrapper(tmp_path):
    files = sitl_root.stage_sitl_root(tmp_path, STOCK, "/fw/arduplane")
    lua = sorted(path.name for path in sitl_root.SITL_LUA_DIR.glob("*.lua"))
    assert set(files) == {
        "bin/arduplane",
        "defaults.parm",
        *(f"seed/scripts/{name}" for name in lua),
        "seed/terrain/N40E044.DAT",
    }
    for relative, digest in files.items():
        assert hashlib.sha256((tmp_path / relative).read_bytes()).hexdigest() == digest
    # No eeprom: every instance boots fresh.
    assert not list(tmp_path.rglob("eeprom.bin"))
    assert all(b"\r\n" not in (tmp_path / "seed/scripts" / name).read_bytes() for name in lua)
    defaults = (tmp_path / "defaults.parm").read_text(encoding="ascii")
    assert "ROLL_LIMIT_DEG 45\n" in defaults and "KEEP_ME 3\n" in defaults
    terrain = (tmp_path / "seed/terrain/N40E044.DAT").read_bytes()
    assert terrain == (sitl_root.SITL_TERRAIN_DIR / "N40E044.DAT").read_bytes()


def test_pinned_sitl_terrain_tile_is_complete_and_unchanged():
    # Generated by ArduPilot's create_terrain.py (SRTM3, 100 m) and checked
    # with its --test; a change is a different simulated ground.
    tile = sitl_root.SITL_TERRAIN_DIR / "N40E044.DAT"
    assert tile.stat().st_size == 3_080_192
    assert hashlib.md5(tile.read_bytes()).hexdigest() == "3b13079ae20144e17d842bb6a10d8543"


def _tile(directory: Path, side: int = 11) -> Path:
    path = directory / "N40E044.hgt"
    np.full(side * side, 1300, dtype=">i2").tofile(path)
    return path


