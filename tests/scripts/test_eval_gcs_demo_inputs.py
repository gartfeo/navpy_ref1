def test_manifest_and_host_sidecar(tmp_path, monkeypatch):
    monkeypatch.setattr(inputs, "navpy_inputs", lambda: {"dem": {}})
    env = {"PATH": "C:\\bin"}
    manifest = inputs.write_input_manifest(
        tmp_path, env, {"files": {"a": "1"}}, "/home/u/r", {"confirmation_delay_s": 15.0}
    )
    written = json.loads((tmp_path / inputs.INPUT_MANIFEST).read_text(encoding="utf-8"))
    assert written == manifest
    assert set(manifest) == {
        "schema", "source", "run_options", "scenario_sha256", "sitl", "navpy", "environment",
    }
    assert manifest["run_options"] == {"confirmation_delay_s": 15.0}
    assert set(manifest["source"]) == {"git_head", "uncommitted_diff_sha256", "untracked_sha256"}
    assert str(tmp_path) not in json.dumps(manifest)
    host = json.loads((tmp_path / inputs.INPUT_MANIFEST_HOST).read_text(encoding="utf-8"))
    assert host == {"run_dir": str(tmp_path.resolve()), "sitl_root": "/home/u/r"}


def _fake_wsl(monkeypatch, tmp_path, home="/home/u"):
    """Run the root preparation against a recorded fake WSL."""
    scripts: list[str] = []
    staged_hashes: dict[str, str] = {}

    def wsl_output(script):
        scripts.append(script)
        if script.startswith("printf %s"):
            return home
        if script.startswith("cat "):
            return STOCK
        if script.startswith("set -e"):
            return "".join(f"{digest}  ./{name}\n" for name, digest in staged_hashes.items())
        return "".join(
            f"absent  {home}/{name}\n" if name.startswith(".bash_login") else f"{'ab' * 32}  {home}/{name}\n"
            for name in (*sitl_root.WSL_HOST_FILES, *sitl_root.WSL_LOGIN_PROFILES)
        ) + f"{'cd' * 32}  /etc/profile.d/router.sh\n"

    real_stage = sitl_root.stage_sitl_root

    def stage(directory, stock, firmware):
        staged_hashes.update(real_stage(directory, stock, firmware))
        return dict(staged_hashes)

    monkeypatch.setattr(sitl_root, "_wsl_output", wsl_output)
    monkeypatch.setattr(sitl_root, "_wsl_path", lambda path: "/mnt/c/run dir/it's; rm -rf ~ #")
    monkeypatch.setattr(sitl_root, "stage_sitl_root", stage)
    return scripts


def test_prepare_quotes_every_wsl_path_and_hashes_host_inputs(monkeypatch, tmp_path):
    run_dir = tmp_path / "it's; rm -rf ~ #"
    run_dir.mkdir()
    scripts = _fake_wsl(monkeypatch, tmp_path)
    root, section, host = sitl_root.prepare_sitl_root(run_dir)
    copy = next(script for script in scripts if script.startswith("set -e"))
    # The hostile staging path stays one quoted word.
    assert "'/mnt/c/run dir/it'\"'\"'s; rm -rf ~ #'" in copy
    assert section["host_files"]["ardupilot/Tools/autotest/run_swarm.sh"] == "ab" * 32
    assert section["host_files"][".bashrc"] == "ab" * 32
    assert section["host_files"][".bash_login"] is None
    # bash -lc also reads /etc; an export there must change the manifest.
    assert section["host_files"]["/etc/profile.d/router.sh"] == "cd" * 32
    host_script = next(script for script in scripts if "/etc/profile.d/*.sh" in script)
    assert "/etc/profile " in host_script and "/etc/bash.bashrc" in host_script
    assert host == root.root and root.root.startswith("/home/u/navpy-eval-roots/it-s--rm--rf")
